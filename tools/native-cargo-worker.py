BUDGET = 1073741824
PROGRAM = '''use std::io::Read;
const CHUNK: usize = 64 * 1024 * 1024;
fn main() {
    let mut text = String::new();
    std::io::stdin().read_to_string(&mut text).unwrap();
    let n: u64 = text.trim().parse().unwrap();
    let chunk = (n as usize).min(CHUNK).max(1);
    let bytes = vec![1u8; chunk];
    let mut total = 0u64;
    for i in 0..n { total += bytes[(i % chunk as u64) as usize] as u64; }
    let mut buffer = itoa::Buffer::new();
    println!("{}", buffer.format(total));
}
'''
ISOLATED_BUILD_SCRIPT = '''fn main() {
    assert!(!std::path::Path::new("/home/chili-runner").exists());
    assert!(std::env::var("CHILI_BUILD_SECRET").is_err());
    assert!(std::net::TcpStream::connect("1.1.1.1:80").is_err());
}
'''
RANDOM_BUILD_SCRIPT = '''use std::io::Read;
fn main() {
    let mut seed = [0u8; 8];
    std::fs::File::open("/dev/urandom").unwrap().read_exact(&mut seed).unwrap();
    let path = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("seed.rs");
    std::fs::write(path, format!("pub const SEED: u64 = {};", u64::from_le_bytes(seed))).unwrap();
}
'''


def lock_block(name):
    text = (LAB / "vendor-Cargo.lock").read_text()
    return next("[[package]]\n" + block.strip() + "\n" for block in text.split("[[package]]\n")[1:]
                if block.startswith(f'name = "{name}"\n'))


def tampered(lock):
    return lock.replace(lock.split('checksum = "')[1][:64], "f" * 64)


def project(path, program=PROGRAM, build_script=ISOLATED_BUILD_SCRIPT, extra=None, lock_edit=None):
    (path / "src").mkdir(parents=True)
    extra = extra or {}
    dependencies = ['itoa = "=1.0.15"', *(f'{name} = "={version}"' for name, (version, _) in extra.items())]
    (path / "Cargo.toml").write_text('[package]\nname = "bytesum"\nversion = "0.1.0"\nedition = "2021"\n'
                                     'build = "build.rs"\n\n[dependencies]\n' + "\n".join(dependencies) + "\n")
    names = ["itoa", *extra]
    lock = ('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n'
            '[[package]]\nname = "bytesum"\nversion = "0.1.0"\ndependencies = [\n'
            + "".join(f' "{name}",\n' for name in sorted(names)) + ']\n\n' + lock_block("itoa"))
    for name, (version, checksum) in extra.items():
        lock += (f'\n[[package]]\nname = "{name}"\nversion = "{version}"\n'
                 f'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "{checksum}"\n')
    (path / "Cargo.lock").write_text(lock_edit(lock) if lock_edit else lock)
    (path / "build.rs").write_text(build_script)
    (path / "src/main.rs").write_text(program)
    (path / "contract.txt").write_text("Exact sum of n bytes of value one.\n")


def main():
    relative = next(line.split(":", 2)[2] for line in Path("/proc/self/cgroup").read_text().splitlines() if line.startswith("0::"))
    service = Path("/sys/fs/cgroup") / relative.lstrip("/")
    (service / "manager").mkdir()
    (service / "manager/cgroup.procs").write_text(str(os.getpid()))
    (service / "cgroup.subtree_control").write_text("+memory +pids +cpu")
    parent = service / "experiments"
    parent.mkdir()
    (parent / "cgroup.subtree_control").write_text("+memory +pids +cpu")
    os.environ.update(CHILI_BUILD_SECRET="not-mounted")
    policy_path = LAB / "artifact-policy.json"
    policy_path.write_text(json.dumps({"schema_version": "0.1", "format": "elf64-lsb-x86_64", "maximum_bytes": 8388608}))
    manifest = json.loads((LAB / "source/examples/experiment.json").read_text())
    manifest["target"].update(rootfs=str(LAB / "compiler-rootfs"), rootfs_hash=tree_hash(LAB / "compiler-rootfs"),
        command=["/usr/bin/python3", "-I", "-B", "/fixtures/cargo-build.py"], build_identity=(LAB / "toolchain-version.txt").read_text())
    workload = manifest["workloads"][0]
    workload.update(input=str(LAB / "empty-input"), arguments=["compile"], oracle={"kind": "build_elf_v1", "policy_path": str(policy_path), "policy_hash": file_hash(policy_path)})
    workload.pop("expected_stdout_hash")
    manifest["isolation"].update(cgroup_parent=str(parent), seccomp="pilot_build_v1", scratch_bytes=268435456,
        pids=128, file_descriptors=1024, cpu={"quota_usec": 100000, "period_usec": 100000})
    manifest["limits"].update(timeout_seconds=180, output_bytes_per_stream=8388608, experiment_seconds=3600)
    work = LAB / "build-validation"
    work.mkdir()
    compiler_manifest = work / "compile-manifest.json"
    compiler_manifest.write_text(json.dumps(manifest, indent=2))
    unvendored = {"ryu": ("1.0.20", "0" * 64)}
    controls = (("compile", {}, "retained"),
                ("unvendored-dependency", {"extra": unvendored}, "rejected"),
                ("tampered-lockfile", {"lock_edit": tampered}, "rejected"),
                ("nondeterministic-build-script", {"build_script": RANDOM_BUILD_SCRIPT,
                    "program": 'include!(concat!(env!("OUT_DIR"), "/seed.rs"));\nfn main() { println!("{}", SEED); }\n'}, "rejected"))
    results = []
    for name, options, expected in controls:
        source = LAB / ("rust-" + name)
        project(source, **options)
        try:
            outcome = compile_candidate(source, compiler_manifest, work / name, BUDGET, time.monotonic()+600,
                                        evidence_root=work / "evidence")["status"]
        except ValueError:
            outcome = json.loads((work / name / "build-record.json").read_text())["status"]
        results.append({"mode": name, "outcome": outcome})
        assert outcome == expected, (name, outcome)
    runtime = copy.deepcopy(manifest)
    runtime["target"].update(rootfs=str(LAB / "rootfs"), rootfs_hash=tree_hash(LAB / "rootfs"),
        command=["/usr/bin/python3", "-I", "-B", "/fixtures/run-compiled.py"])
    runtime["isolation"].update(seccomp="pilot_allowlist_v1", scratch_bytes=1048576, pids=32, file_descriptors=64)
    runtime["limits"].update(timeout_seconds=15, output_bytes_per_stream=65536, experiment_seconds=300)
    public_input = LAB / "compiled-input"
    public_input.write_text("67108864\n")
    runtime["workloads"][0].pop("oracle")
    runtime["workloads"][0].update(arguments=[], input=str(public_input), input_hash=file_hash(public_input),
        expected_stdout_hash=hashlib.sha256(b"67108864\n").hexdigest())
    direct = copy.deepcopy(runtime)
    direct["target"]["source_mount"] = {"path": str(work / "compile/artifacts"), "tree_hash": tree_hash(work / "compile/artifacts")}
    direct["evidence_directory"] = str(work / "evidence")
    executed = run_trial(direct, "correct", 268435456)
    assert executed["outcome"] == "pass", executed
    runtime_manifest = work / "runtime-manifest.json"
    runtime_manifest.write_text(json.dumps(runtime, indent=2))
    # The controller and final gate compile Rust candidates through the same worker.
    vault = LAB / "compiled-grader-vault"
    vault.mkdir(mode=0o700)
    vault.chmod(0o700)
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    key = Ed25519PrivateKey.generate()
    key_path = vault / "key"
    key_path.write_bytes(key.private_bytes_raw())
    key_path.chmod(0o600)
    hidden_input = vault / "input"
    hidden_input.write_text("34567891\n")
    hidden_input.chmod(0o600)
    sealed_runtime = copy.deepcopy(runtime)
    sealed_runtime["workloads"][0].update(input=str(hidden_input), input_hash=file_hash(hidden_input),
        expected_stdout_hash=hashlib.sha256(b"34567891\n").hexdigest())
    sealed_manifest = vault / "runtime.json"
    sealed_manifest.write_text(json.dumps(sealed_runtime, indent=2))
    sealed_manifest.chmod(0o600)
    sealed_compiler = vault / "compiler.json"
    sealed_compiler.write_bytes(compiler_manifest.read_bytes())
    sealed_compiler.chmod(0o600)
    sealed_policy = vault / "policy.json"
    sealed_policy.write_text(json.dumps({"schema_version": "0.1", "campaign": "cargo-fixture",
        "manifest": str(sealed_manifest), "manifest_sha256": file_hash(sealed_manifest),
        "build": {"manifest": str(sealed_compiler), "manifest_sha256": file_hash(sealed_compiler), "memory_budget": BUDGET},
        "benchmark_workload": "correct", "transfer_budget": 268435456, "repetitions": 3, "seed": 17,
        "wall_seconds": 900, "max_trials": 14, "maximum_latency_regression": 1.0, "minimum_memory_improvement": .1}, indent=2))
    sealed_policy.chmod(0o600)
    baseline = LAB / "cargo-baseline"
    candidate = LAB / "cargo-candidate"
    project(baseline)
    project(candidate, program=PROGRAM.replace("64 * 1024 * 1024", "8 * 1024 * 1024"))
    config = initialize(baseline, ["NEVER_EXECUTE_HOST_TESTS"], protected_paths=["contract.txt"])
    plan = {"schema_version": "0.1", "concept": "Rust byte sum with bounded live storage",
        "project_config": str(config), "benchmark_command": ["NEVER_EXECUTE_HOST_BENCHMARK"], "objective": "enforced_budget_bytes",
        "evaluation": {"backend": "linux_cgroup", "manifest": str(runtime_manifest), "benchmark_workload": "correct", "initial_budget": 100663296,
            "build": {"manifest": str(compiler_manifest), "memory_budget": BUDGET}},
        "acceptance": {"campaign": "cargo-fixture", "public_key": key.public_key().public_bytes_raw().hex(),
            "policy_sha256": file_hash(sealed_policy), "evaluator_sha256": acceptance.implementation()},
        "quantum": 4096, "minimum_target": 8388608, "reductions": [.5], "repetitions": 2,
        "confirmation_repetitions": 2, "regression_limits": {}, "max_generations": 1, "wall_seconds": 1800}
    plan_path = work / "development-plan.json"
    plan_path.write_text(json.dumps(plan, indent=2))
    research = work / "research.json"
    research.write_text(json.dumps({"hypothesis": "Smaller live chunks reduce memory", "mechanism": "Bounded storage",
        "falsification": "Wrong sum or OOM", "sources": [{"reference": "owner:cargo-fixture", "supports": "Scripted Rust source variants"}]}))
    session = LAB / "compiled-development-session"
    dev.create(plan_path, session)
    state = dev.submit(session, candidate, research)
    assert state["generations"][-1]["decision"] == "accepted_experimental", state["generations"][-1]
    receipt = acceptance.grade(dev.acceptance_request(session), sealed_policy, key_path, vault)
    assert receipt["body"]["verdict"] == "passed", receipt
    receipt_path = LAB / "compiled-receipt.json"
    receipt_path.write_text(json.dumps(receipt, indent=2))
    state = dev.accept(session, receipt_path)
    assert state["champions"][state["champion"]]["acceptance_state"] == "verified_champion"
    leaks = sorted(path.name for path in parent.glob("chili-*") if path.is_dir())
    assert not leaks, leaks
    summary = {"status": "passed", "toolchain": "rustc/cargo 1.93.1, vendored itoa 1.0.15",
        "compiler_controls": results, "compiled_runtime": "pass",
        "compiled_controller": "accepted_experimental", "compiled_sealed_gate": "passed",
        "remaining_cgroups": leaks, "scope": "offline Cargo build/export/run and final-gate fixture; no model calls"}
    (LAB / "native-summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
